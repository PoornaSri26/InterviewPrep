import React, { useState, useEffect, useCallback } from 'react';
import type { RepoCatalogEntry } from './data/repoCatalog';
import { LandingPage } from './components/LandingPage';
import { Navbar } from './components/Navbar';
import { DashboardView } from './components/DashboardView';
import { MockInterviewView } from './components/MockInterviewView';
import { MergedDsaView } from './components/MergedDsaView';
import { CodeSandboxView } from './components/CodeSandboxView';
import { SystemDesignView } from './components/SystemDesignView';
import { BehavioralView } from './components/BehavioralView';
import { RoadmapView } from './components/RoadmapView';
import { ResourcesView } from './components/ResourcesView';
import { SettingsModal } from './components/SettingsModal';
import { FlashcardsView } from './components/FlashcardsView';
import { CompanyPrepView } from './components/CompanyPrepView';
import { OfferComparatorView } from './components/OfferComparatorView';
import { DailyChallengeView } from './components/DailyChallengeView';
import { GlobalSearch } from './components/GlobalSearch';
import { QuestionBankView } from './components/QuestionBankView';
import { PatternLearningView } from './components/PatternLearningView';
import { BugHuntView } from './components/BugHuntView';
import { ComplexityGymView } from './components/ComplexityGymView';

import { 
  getStoredProblems, 
  saveProblems, 
  updateProblemSRS, 
  getStoredMocks, 
  saveMockSession, 
  getStoredStarStories, 
  saveStarStories,  getStoredRoadmap,
  saveRoadmap,
  getStreak,
  getStoredFlashcards,
  saveFlashcards,
  updateFlashcardSRS,
  getStoredOffers,
  saveOffers,
  getStoredSolutions,
  saveSolutions
} from './services/storage';

import { Problem, MockInterviewSession, StarStory, RoadmapWeek, Flashcard, OfferPackage, ProblemSolution, SolutionMap, LeetcodeSheetProblem, SheetMetaMap } from './types';
import { RepoBankFile, RepoFlashcardsFile, RepoRoadmapsFile, BankProblem, BankCard } from './types/minedContent';
import { repoCatalog } from './data/repoCatalog';
import { initialProblems } from './data/problemsData';
import { initialStarStories } from './data/behavioralData';
import { initialRoadmap } from './data/roadmapData';
import { initialFlashcards } from './data/flashcardsData';
import { initialOffers } from './data/offersData';
import { getStoredRepoCatalogEnabled } from './services/storage';
import { companyProfiles } from './data/companyData';
import { systemDesignTopics } from './data/systemDesignData';
import { allResources } from './data/resourcesData';
import { ResumeData } from './services/resumeParser';

export function App() {
  const [showLanding, setShowLanding] = useState<boolean>(true);
  const [activeTab, setActiveTab] = useState<string>('dashboard');
  const [activeProblemId, setActiveProblemId] = useState<string | null>(null);
  const [settingsOpen, setSettingsOpen] = useState(false);
  const [searchOpen, setSearchOpen] = useState(false);
  const [sheetCompanyRequest, setSheetCompanyRequest] = useState<string | null>(null);
  const [sheetMeta, setSheetMeta] = useState<SheetMetaMap | null>(null);
  const [sheetInfo, setSheetInfo] = useState<{ companies: number; totalProblems: number } | null>(null);
  // Lazily-mined repo content (public/*.json, generated by `npm run mine`)
  const [repoBank, setRepoBank] = useState<RepoBankFile | null>(null);
  const [bankDecks, setBankDecks] = useState<RepoFlashcardsFile | null>(null);
  const [repoPlans, setRepoPlans] = useState<RepoRoadmapsFile | null>(null);

  // Core Data State
  const [problems, setProblems] = useState<Problem[]>(getStoredProblems);
  const [mockSessions, setMockSessions] = useState<MockInterviewSession[]>(getStoredMocks);
  const [starStories, setStarStories] = useState<StarStory[]>(getStoredStarStories);
  const [roadmap, setRoadmap] = useState<RoadmapWeek[]>(getStoredRoadmap);
  const [flashcards, setFlashcards] = useState<Flashcard[]>(getStoredFlashcards);
  const [offers, setOffers] = useState<OfferPackage[]>(getStoredOffers);
  const [solutions, setSolutions] = useState<SolutionMap>(getStoredSolutions);
  const [repoCatalogEnabled, setRepoCatalogEnabled] = useState<boolean>(getStoredRepoCatalogEnabled);
  const [streak, setStreak] = useState<{ current: number; max: number }>({ current: 1, max: 1 });
  const [resumeData, setResumeData] = useState<ResumeData | null>(null);

  useEffect(() => {
    setStreak(getStreak());
  }, []);

  // Mined repo content: bank, flashcard decks, roadmap plans (all optional — app degrades gracefully)
  useEffect(() => {
    const safeFetch = (url: string) => fetch(url, { cache: 'no-store' })
      .then((r) => {
        if (!r.ok) return null;
        const ct = r.headers.get('content-type') || '';
        if (ct.includes('text/html')) return null;
        return r.text();
      })
      .then((t) => {
        if (!t) return null;
        try { return JSON.parse(t); } catch { return null; }
      })
      .catch(() => null);
    safeFetch('/repo-bank.json').then((j) => j && setRepoBank(j));
    safeFetch('/repo-flashcards.json').then((j) => j && setBankDecks(j));
    safeFetch('/repo-roadmaps.json').then((j) => j && setRepoPlans(j));
  }, []);

  // One shared sheet index — feeds tracker badges, merged stats and global search
  useEffect(() => {
    fetch('/leetcode-sheets.json', { cache: 'no-store' })
      .then((r) => {
        if (!r.ok) return null;
        const ct = r.headers.get('content-type') || '';
        if (ct.includes('text/html')) return null;
        return r.text();
      })
      .then((text) => {
        if (!text) return;
        try {
          const json = JSON.parse(text);
          const meta: SheetMetaMap = {};
          for (const sheet of json.sheets || []) {
            for (const p of sheet.problems || []) {
              const key = String(p.title).toLowerCase();
              const entry = meta[key];
              if (!entry) {
                meta[key] = { frequency: p.frequency, companies: [sheet.company] };
              } else {
                if (!entry.companies.includes(sheet.company)) entry.companies.push(sheet.company);
                if (p.frequency > entry.frequency) entry.frequency = p.frequency;
              }
            }
          }
          setSheetMeta(meta);
          setSheetInfo({ companies: json.companyCount, totalProblems: json.totalProblems });
        } catch (e) {
          // ignore parse errors
        }
      })
      .catch(() => {});
  }, []);

  // Handlers
  /** Central navigation — also clears pending cross-module requests. */
  const navigate = (tab: string) => {
    setActiveTab(tab);
    setSheetCompanyRequest(null);
  };

  /** Company Prep → LeetCode Sheets deep link. */
  const handleOpenSheetForCompany = (company: string) => {
    setActiveTab('sheets');
    setSheetCompanyRequest(company);
  };

  /** Global search jump. */
  const handleJump = (tab: string, key?: string) => {
    if (tab === 'sheets' && key) {
      setActiveTab('sheets');
      setSheetCompanyRequest(key);
    } else {
      setActiveTab(tab);
    }
  };

  const handleSolveProblem = (problemId: string) => {
    setActiveProblemId(problemId);
    setActiveTab('sandbox');
  };

  const handleGradeProblem = (problemId: string, quality: 0 | 1 | 2 | 3 | 4 | 5) => {
    const updated = updateProblemSRS(problemId, quality);
    setProblems(updated);
  };

  const handleAddCustomProblem = (newProblem: Problem) => {
    const normTitle = newProblem.title.trim().toLowerCase();
    // dedupe by id OR normalized title (stops sheet imports cloning e.g. Two Sum)
    if (problems.some((p) => p.id === newProblem.id || p.title.trim().toLowerCase() === normTitle)) return;
    const updated = [newProblem, ...problems];
    setProblems(updated);
    saveProblems(updated);
  };

  /** LeetCode Sheet → DSA Tracker import. */
  const handleImportSheetProblem = (row: LeetcodeSheetProblem, company: string) => {
    const difficulty = row.difficulty === 'EASY' ? 'Easy' : row.difficulty === 'HARD' ? 'Hard' : 'Medium';
    const imported: Problem = {
      id: `sheet-${row.slug}`,
      title: row.title,
      difficulty,
      category: row.topics[0] || 'LeetCode',
      companies: [company],
      description: `Imported from your ${company} company sheet (frequency ${row.frequency}, acceptance ${row.acceptance}%).\n\nSolve it here or open the original: ${row.link}`,
      examples: [],
      constraints: [],
      starterCodeJs: `// ${row.title}\nfunction solve(\n) {\n  // your solution\n}\n`,
      starterCodePy: `# ${row.title}\ndef solve():\n    # your solution\n    pass\n`,
      testCases: [],
      solutionCodeJs: '',
      timeComplexity: '—',
      spaceComplexity: '—',
      hints: row.topics.length ? [`Related topics: ${row.topics.join(', ')}`] : [],
      sourceUrl: row.link,
      status: 'unsolved',
      intervalDays: 1,
      easeFactor: 2.5,
      repetitionCount: 0
    };
    handleAddCustomProblem(imported);
  };

  /** Repo Bank (mined GitHub content) → DSA Tracker batch import. Returns how many were added. */
  const handleImportFromBank = (items: BankProblem[]): number => {
    const existingTitles = new Set(problems.map((p) => p.title.trim().toLowerCase()));
    const additions: Problem[] = [];
    for (const b of items) {
      const norm = b.title.trim().toLowerCase();
      if (!norm || existingTitles.has(norm)) continue;
      existingTitles.add(norm);
      additions.push({
        id: `bank-${b.id}`,
        title: b.title,
        difficulty: b.difficulty === 'Easy' ? 'Easy' : b.difficulty === 'Hard' ? 'Hard' : 'Medium',
        category: b.topics[0] || 'Repo Bank',
        companies: [],
        description: `Imported from the repo bank — mined from ${b.sourceRepo}.\n\nOpen the source: ${b.url}`,
        examples: [],
        constraints: [],
        starterCodeJs: `// ${b.title}\nfunction solve() {\n  // your solution\n}\n`,
        starterCodePy: `# ${b.title}\ndef solve():\n    pass\n`,
        testCases: [],
        solutionCodeJs: '',
        timeComplexity: '—',
        spaceComplexity: '—',
        hints: b.topics.length ? [`Related topics: ${b.topics.join(', ')}`] : [],
        sourceUrl: b.url,
        status: 'unsolved',
        intervalDays: 1,
        easeFactor: 2.5,
        repetitionCount: 0
      });
    }
    if (additions.length) {
      const updated = [...additions, ...problems];
      setProblems(updated);
      saveProblems(updated);
    }
    return additions.length;
  };

  /** Mined Q/A deck → Flashcards import (dedupe by id and normalized front). Returns added count. */
  const handleImportCards = (cards: BankCard[], deckName: string): number => {
    const existingIds = new Set(flashcards.map((c) => c.id));
    const existingFronts = new Set(flashcards.map((c) => c.front.trim().toLowerCase().slice(0, 80)));
    const additions: Flashcard[] = [];
    for (const c of cards) {
      if (existingIds.has(c.id)) continue;
      const key = c.front.trim().toLowerCase().slice(0, 80);
      if (existingFronts.has(key)) continue;
      existingIds.add(c.id);
      existingFronts.add(key);
      additions.push({
        id: c.id,
        topic: c.sourceRepo.split('/').pop()?.replace(/[-_]+/g, ' ') || 'Repo Bank',
        deck: deckName,
        front: c.front,
        back: c.back,
        status: 'new',
        intervalDays: 1,
        easeFactor: 2.5,
        repetitionCount: 0
      });
    }
    if (additions.length) {
      const updated = [...flashcards, ...additions];
      setFlashcards(updated);
      saveFlashcards(updated);
    }
    return additions.length;
  };

  /**
   * GitHub repo catalog → trackers. A repo has no per-problem metadata of its own,
   * so each import becomes a clearly-labelled "Repo study" task (DSA tracker) or a
   * summary card (Flashcards) that links back to the repository.
   */
  const handleImportRepoPack = (entries: RepoCatalogEntry[], kind: 'problem' | 'flashcard'): number => {
    if (kind === 'problem') {
      return handleImportFromBank(entries.map((e) => ({
        id: `catalog-${e.repo}`,
        title: `Repo study: ${e.repo}`,
        slug: e.repo.split('/').pop() || e.repo,
        url: e.url,
        difficulty: 'Medium' as const,
        topics: [e.category],
        sourceRepo: e.repo,
        sourceStars: e.stars
      })));
    }
    return handleImportCards(entries.map((e) => ({
      id: `card-catalog-${e.repo}`,
      front: `What does ${e.repo} cover, and why is it useful for interview prep?`,
      back: `${e.category} · ★ ${e.stars}. ${e.description ?? e.name}. ${e.url}`,
      sourceRepo: e.repo
    })), 'Repo Catalog');
  };

  /** Coach drills → Flashcards, so the fix is rehearsed rather than just read. */
  const handleAddCoachCards = (cards: { front: string; back: string }[]): number =>
    handleImportCards(
      cards.map((card, index) => ({
        id: `coach-${Date.now()}-${index}`,
        front: card.front,
        back: card.back,
        sourceRepo: 'coach'
      })),
      'Coach Drills'
    );

  /** Q&A Bank → Flashcards, one deck per import so the drill set stays together. */
  const handleAddQuestionCards = (cards: { front: string; back: string }[]): number =>
    handleImportCards(
      cards.map((card, index) => ({
        id: `qbank-${Date.now()}-${index}`,
        front: card.front,
        back: card.back,
        sourceRepo: 'qbank'
      })),
      'Q&A Bank'
    );

  const handleSaveMockSession = (session: MockInterviewSession) => {
    saveMockSession(session);
    setMockSessions([session, ...mockSessions]);
  };

  const handleSaveStory = (story: StarStory) => {
    const existingIndex = starStories.findIndex((s) => s.id === story.id);
    let updated: StarStory[];
    if (existingIndex >= 0) {
      updated = [...starStories];
      updated[existingIndex] = story;
    } else {
      updated = [story, ...starStories];
    }
    setStarStories(updated);
    saveStarStories(updated);
  };

  const handleDeleteStory = (id: string) => {
    const updated = starStories.filter((s) => s.id !== id);
    setStarStories(updated);
    saveStarStories(updated);
  };

  const handleToggleMilestone = (weekNum: number, milestoneId: string) => {
    const updated = roadmap.map((week) => {
      if (week.weekNumber !== weekNum) return week;
      return {
        ...week,
        milestones: week.milestones.map((m) =>
          m.id === milestoneId ? { ...m, completed: !m.completed } : m
        )
      };
    });
    setRoadmap(updated);
    saveRoadmap(updated);
  };

  const handleGradeFlashcard = (cardId: string, quality: 0 | 1 | 2 | 3 | 4 | 5) => {
    const updated = updateFlashcardSRS(cardId, quality);
    setFlashcards(updated);
  };

  const handleSaveOffer = (offer: OfferPackage) => {
    const existingIndex = offers.findIndex((o) => o.id === offer.id);
    let updated: OfferPackage[];
    if (existingIndex >= 0) {
      updated = [...offers];
      updated[existingIndex] = offer;
    } else {
      updated = [...offers, offer];
    }
    setOffers(updated);
    saveOffers(updated);
  };

  const handleDeleteOffer = (id: string) => {
    const updated = offers.filter((o) => o.id !== id);
    setOffers(updated);
    saveOffers(updated);
  };

  const handleSaveSolution = (slug: string, solution: ProblemSolution) => {
    const updated = { ...solutions, [slug]: solution };
    setSolutions(updated);
    saveSolutions(updated);
  };

  const handleResetAllData = () => {
    localStorage.clear();
    setProblems(initialProblems);
    setMockSessions([]);
    setStarStories(initialStarStories);
    setRoadmap(initialRoadmap);
    setFlashcards(initialFlashcards);
    setOffers(initialOffers);
    setSolutions({});
    setStreak({ current: 1, max: 1 });
  };

  if (showLanding) {
    return <LandingPage onEnterApp={() => setShowLanding(false)} />;
  }

  return (
    <div className="app-container">
      {/* Navigation Header */}
      <Navbar
        activeTab={activeTab}
        setActiveTab={navigate}
        streak={streak}
        onOpenSettings={() => setSettingsOpen(true)}
        onOpenSearch={() => setSearchOpen(true)}
        onGoHome={() => setShowLanding(true)}
      />


      {/* Main Content Area */}
      <main className="main-content">
        {activeTab === 'dashboard' && (
          <DashboardView
            problems={problems}
            mockSessions={mockSessions}
            starStories={starStories}
            roadmap={roadmap}
            onNavigate={navigate}
            onSolveProblem={handleSolveProblem}
          />

        )}

        {activeTab === 'mock' && (
          <MockInterviewView
            onSaveSession={handleSaveMockSession}
            mockHistory={mockSessions}
            onAddCoachCards={handleAddCoachCards}
            resumeData={resumeData}
            onResumeUpload={setResumeData}
          />

        )}

        {activeTab === 'dsa' && (
          <MergedDsaView
            initialMode="tracker"
            problems={problems}
            onSolveProblem={handleSolveProblem}
            onGradeProblem={handleGradeProblem}
            onAddCustomProblem={handleAddCustomProblem}
            solutions={solutions}
            onSaveSolution={handleSaveSolution}
            openCompany={null}
            onOpenCompanyConsumed={() => {}}
            onAddToTracker={handleImportSheetProblem}
            sheetMeta={sheetMeta}
            sheetInfo={sheetInfo}
            repoBank={repoBank}
            onImportFromBank={handleImportFromBank}
          />

        )}

        {activeTab === 'sandbox' && (
          <CodeSandboxView
            problems={problems}
            activeProblemId={activeProblemId}
            onSelectProblem={setActiveProblemId}
            onGradeProblem={handleGradeProblem}
          />

        )}

        {activeTab === 'system-design' && <SystemDesignView />}

        {activeTab === 'behavioral' && (
          <BehavioralView
            stories={starStories}
            onSaveStory={handleSaveStory}
            onDeleteStory={handleDeleteStory}
          />

        )}

        {activeTab === 'roadmap' && (
          <RoadmapView
            roadmap={roadmap}
            onToggleMilestone={handleToggleMilestone}
            repoPlans={repoPlans}
          />

        )}

        {activeTab === 'resources' && (
          <ResourcesView
            repoCatalog={repoCatalogEnabled ? repoCatalog : []}
            onImportRepoPack={handleImportRepoPack}
            onToggleRepoCatalog={() => {
              setRepoCatalogEnabled((prev) => {
                const next = !prev;
                localStorage.setItem('interview_os_repo_catalog_enabled', String(next));
                return next;
              });
            }}
          />
        )}

        {activeTab === 'daily' && (
          <DailyChallengeView
            problems={problems}
            onSolveProblem={handleSolveProblem}
          />

        )}

        {activeTab === 'flashcards' && (
          <FlashcardsView
            cards={flashcards}
            onGradeCard={handleGradeFlashcard}
            bankDecks={bankDecks}
            onImportCards={handleImportCards}
          />

        )}

        {activeTab === 'qbank' && <QuestionBankView onAddCards={handleAddQuestionCards} />}

        {activeTab === 'companies' && (
          <CompanyPrepView onOpenSheet={handleOpenSheetForCompany} />
        )}

        {activeTab === 'offers' && (
          <OfferComparatorView
            offers={offers}
            onSaveOffer={handleSaveOffer}
            onDeleteOffer={handleDeleteOffer}
          />

        )}

        {activeTab === 'sheets' && (
          <MergedDsaView
            initialMode="sheets"
            problems={problems}
            onSolveProblem={handleSolveProblem}
            onGradeProblem={handleGradeProblem}
            onAddCustomProblem={handleAddCustomProblem}
            solutions={solutions}
            onSaveSolution={handleSaveSolution}
            openCompany={sheetCompanyRequest}
            onOpenCompanyConsumed={() => setSheetCompanyRequest(null)}
            onAddToTracker={handleImportSheetProblem}
            sheetMeta={sheetMeta}
            sheetInfo={sheetInfo}
            repoBank={repoBank}
            onImportFromBank={handleImportFromBank}
          />

        )}

        {activeTab === 'patterns' && <PatternLearningView />}
        {activeTab === 'bughunt' && <BugHuntView />}
        {activeTab === 'complexity' && <ComplexityGymView />}
      </main>

      {/* Cross-Module Global Search */}
      <GlobalSearch
        isOpen={searchOpen}
        onClose={() => setSearchOpen(false)}
        data={{
          problems,
          flashcards,
          companies: companyProfiles,
          systemTopics: systemDesignTopics,
          resources: allResources,
                      repoCatalog: repoCatalogEnabled ? repoCatalog : []
        }}
        onJump={handleJump}
      />


      {/* Settings & Portability Modal */}
      <SettingsModal
        isOpen={settingsOpen}
        onClose={() => setSettingsOpen(false)}
        problems={problems}
        mocks={mockSessions}
        starStories={starStories}
        roadmap={roadmap}
        flashcards={flashcards}
        offers={offers}
        solutions={solutions}
        onResetAllData={handleResetAllData}
      />

    </div>
  );
}

export default App;
